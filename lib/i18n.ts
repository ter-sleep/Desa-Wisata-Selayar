export type Message = keyof typeof englishMessages
type Parameters = Record<string, string | number>

function isMessage(value: string): value is Message {
  return Object.hasOwn(englishMessages, value)
}

export function translate(language: Language, message: Message, parameters: Parameters = {}): string {
  const text = language === 'en' ? englishMessages[message] : message
  return text.replace(/\{(\w+)\}/g, (_, name: string) => {
    if (!Object.hasOwn(parameters, name)) throw new Error(`Missing translation parameter: ${name}`)
    return String(parameters[name])
  })
}

// Editorial translations apply only to exact known text; new CMS content remains unchanged.
export function localizeContent(language: Language, text: string): string {
  return isMessage(text) ? translate(language, text) : text
}
